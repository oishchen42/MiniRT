#include <minirt.h>

void	from_high_2_low(t_vcpnt *vcpnt)
{
	vcpnt->vp[0] /= 255.0;
	vcpnt->vp[1] /= 255.0;
	vcpnt->vp[2] /= 255.0;
	vcpnt->vp[3] = 1.0;
}
